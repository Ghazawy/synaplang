def estimate_tokens(code: str) -> int:
    """Accurate BPE / LLM token count estimation based on word/symbol splitting."""
    # Split on whitespace and punctuation tokens
    tokens = re.findall(r"\w+|[^\w\s]", code, re.UNICODE)
    return len(tokens)

